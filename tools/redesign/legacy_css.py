"""Build assets/rr-legacy.css: the old theme/style/trust CSS, scoped to <main class="legacy">,
re-pointed at the v2 tokens, so pages not yet on v2 templates keep their layout inside the new shell."""
import os, re

ROOT = os.path.abspath(os.path.join(os.path.dirname(__file__), "..", ".."))
SCOPE = "main.legacy"
SKIP = re.compile(r"^(\.ubar|\.hdr|\.logo|\.menu|\.nav|\.hact|\.ftr|footer|\.qsbar|\.skip|\.draft|html|:root)\b")


def strip_comments(css):
    return re.sub(r"/\*.*?\*/", "", css, flags=re.S)


def blocks(css):
    """Yield (prelude, body) for each top-level rule."""
    i, n = 0, len(css)
    while i < n:
        j = css.find("{", i)
        if j < 0:
            break
        pre = css[i:j].strip()
        depth, k = 1, j + 1
        while k < n and depth:
            depth += {"{": 1, "}": -1}.get(css[k], 0)
            k += 1
        yield pre, css[j + 1: k - 1]
        i = k


def scope_sel(sel):
    out = []
    for s in sel.split(","):
        s = s.strip()
        if not s or SKIP.match(s):
            continue
        if s == "body":
            out.append(SCOPE)
        elif s.startswith("body "):
            out.append(SCOPE + s[4:])
        elif s.startswith("*"):
            out.append(f"{SCOPE} {s}")
        else:
            out.append(f"{SCOPE} {s}")
    return ",".join(out)


def scope(css):
    res = []
    for pre, body in blocks(css):
        if pre.startswith("@media") or pre.startswith("@supports"):
            inner = scope(body)
            if inner.strip():
                res.append(f"{pre}{{{inner}}}")
        elif pre.startswith("@font-face") or pre.startswith("@keyframes") or pre.startswith("@import"):
            continue
        else:
            sel = scope_sel(pre)
            if sel:
                res.append(f"{sel}{{{body}}}")
    return "\n".join(res)


src = ""
for f in ("theme.css", "style.css", "assets/trust.css", "assets/quote-boost.css"):
    p = os.path.join(ROOT, f)
    if os.path.exists(p):
        src += strip_comments(open(p, encoding="utf-8").read()) + "\n"

root = re.search(r":root\{(.*?)\}", src, re.S).group(1)
# trust.css keeps its own --trust-* tokens in a second :root block; without them legacy .btn / badges render blank.
trust = "".join(";" + m for m in re.findall(r"(--trust-[\w-]+\s*:[^;}]+)", "".join(re.findall(r":root\{(.*?)\}", src, re.S)[1:])))
root = root.rstrip().rstrip(";") + trust
tokens = (f"{SCOPE}{{{root};--line:#e3ded3;--serif:\"Public Sans\",system-ui,sans-serif;--acc:#22231f;--acc-ink:#22231f;--acc-tint:#efebe2;display:block;background:transparent;font:16px/1.6 var(--sans)}}\n"
          f"{SCOPE} .phead{{background:transparent;border-bottom:0}}\n"
          f"{SCOPE} h1,{SCOPE} h2{{font-weight:800;letter-spacing:-.025em}}\n"
          f"{SCOPE} .btn{{border-radius:12px;min-height:48px;background:var(--cta);color:#fff}}\n"
          f"{SCOPE} .btn.ghost,{SCOPE} .btn.light{{background:transparent;color:var(--ink);box-shadow:inset 0 0 0 1px var(--ink)}}\n")
out = "/* GENERATED by tools/redesign/legacy_css.py from the old theme. Edit the generator, not this file. */\n" + tokens + scope(src)
open(os.path.join(ROOT, "assets", "rr-legacy.css"), "w", encoding="utf-8").write(out)
print(f"rr-legacy.css {len(out):,} bytes")
